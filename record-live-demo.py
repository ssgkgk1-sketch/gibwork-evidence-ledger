"""Render a demo from a live-sourced SDK snapshot and actual CLI executions.

This is not a screen recording of the wallet interaction. It must not be
described as a live CLI-to-Gibwork lookup: the authenticated lookup used SDK.
"""

import json
from pathlib import Path
import runpy
import subprocess
import tempfile

import imageio_ffmpeg


ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "media" / "live-demo.mp4"
SNAPSHOT = ROOT / "examples" / "live-snapshot.json"
helpers = runpy.run_path(str(ROOT / "record-demo.py"), run_name="demo_helpers")
frame = helpers["frame"]
run = helpers["run"]
FPS = helpers["FPS"]


def main():
    if OUTPUT.exists():
        raise SystemExit("Refusing to overwrite existing video: " + str(OUTPUT))
    s = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    if s["source"] != "official-sdk-live-wallet-message" or s["task"]["id"] != "1052f22d-3f87-4b1d-b0d7-71a60679e7fa":
        raise RuntimeError("Expected authenticated SDK snapshot")
    with tempfile.TemporaryDirectory(prefix="gibwork-live-demo-") as temp:
        report_dir = Path(temp) / "report"
        tests = run(["node", "--test"])
        check = run(["node", "cli.mjs", "check", "examples/live-manifest.json",
                     "--out", str(report_dir)])
        result = json.loads(check)
        if result["gate"] != "HUMAN_REVIEW_REQUIRED":
            raise RuntimeError("Unexpected live-snapshot report gate")
        report = (report_dir / "report.md").read_text(encoding="utf-8")
        sections = [
            ("Gibwork Evidence Ledger", "Official SDK task lookup + terminal report",
             "Authenticated read-only lookup: 2026-10-11\n"
             "Task: 1052f22d-3f87-4b1d-b0d7-71a60679e7fa\n"
             "Source: official-sdk-live-wallet-message\n"
             "SHA-256: " + s["scopeSha256"],
             "Live-sourced snapshot; wallet signing was not screen-recorded", 7),
            ("Automated tests", "node --test",
             "\n".join(tests.splitlines()[-11:]),
             "Real test execution during this video render", 6),
            ("Generate a report", "node cli.mjs check examples/live-manifest.json --out TEMP/report",
             json.dumps({"gate": result["gate"], "requirements": result["requirements"]}, indent=2),
             "Real CLI execution using the verified live SDK snapshot", 9),
            ("Inspect the output", "report.md (generated by the command)",
             "\n".join(report.splitlines()[:19]),
             "Hashes inventory files; they do not prove organizer approval", 8),
            ("Human checks remain", "report.md (generated by the command)",
             "\n".join(report.splitlines()[-18:]),
             "Two Discord sessions and originality are not asserted", 8),
            ("Scope and limits", "SDK + CLI workflow",
             "Official SDK fetched the real Gibwork task with a wallet message.\n"
             "The CLI then checked local evidence against that snapshot.\n"
             "The CLI adapter itself did not call Gibwork live.\n"
             "No transaction, payment, or bounty submission was made.",
             "Rendered from actual command output, not a screen recording", 7),
        ]
        ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
        proc = subprocess.Popen([ffmpeg, "-y", "-f", "rawvideo", "-vcodec", "rawvideo",
                                 "-s", "1280x720", "-pix_fmt", "rgb24", "-r", str(FPS),
                                 "-i", "-", "-an", "-c:v", "libx264", "-pix_fmt", "yuv420p",
                                 "-movflags", "+faststart", str(OUTPUT)],
                                stdin=subprocess.PIPE, stdout=subprocess.DEVNULL,
                                stderr=subprocess.PIPE)
        try:
            for title, command, output, footer, seconds in sections:
                pixels = frame(title, command, output, footer).tobytes()
                for _ in range(seconds * FPS):
                    proc.stdin.write(pixels)
            proc.stdin.close()
            errors = proc.stderr.read().decode("utf-8", errors="replace")
            if proc.wait() != 0:
                raise RuntimeError("ffmpeg failed: " + errors[-1000:])
        finally:
            if proc.poll() is None:
                proc.kill()
    print(OUTPUT)


if __name__ == "__main__":
    main()
